#!/bin/sh
# Run from the project root with serde-gen installed on PATH.
set -eu

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cd "$work"
cat > first.mbt <<'EOF'
#custom.serde
struct First {
  value : Int
}
EOF
sed 's/First/Second/' first.mbt > second.mbt

usage='Usage: serde-gen INPUT... --output OUTPUT
       serde-gen --package DIR'
[ "$(serde-gen --help)" = "$usage" ]
status=0
serde-gen first.mbt 2> error || status=$?
[ "$status" -eq 2 ]
[ "$(cat error)" = "$usage" ]

serde-gen first.mbt second.mbt --output output.mbt
awk '/impl ToJson for First /{first=NR} /impl ToJson for Second /{second=NR} END {exit !(first && second && first < second)}' output.mbt
cp output.mbt expected
touch -t 200001010000 output.mbt
cp -p output.mbt timestamp
serde-gen first.mbt second.mbt --output output.mbt
cmp output.mbt expected
[ ! output.mbt -nt timestamp ]

printf '%s\n' 'handwritten' > handwritten.mbt
status=0
serde-gen first.mbt --output handwritten.mbt 2> error || status=$?
[ "$status" -eq 1 ]
[ "$(cat error)" = 'serde-gen: refusing to overwrite handwritten.mbt' ]
[ "$(cat handwritten.mbt)" = handwritten ]

cat > broken.mbt <<'EOF'
#custom.serde
struct Broken {
  #custom.serde(path=[])
  value : Int
}
EOF
status=0
serde-gen broken.mbt --output broken.generated.mbt 2> error || status=$?
[ "$status" -eq 1 ]
grep -q '^serde-gen: broken\.mbt-3:3.*: path must be a non-empty array of string keys$' error
[ ! -e broken.generated.mbt ]

cp first.mbt duplicate.mbt
status=0
serde-gen first.mbt duplicate.mbt --output duplicate.generated.mbt 2> error || status=$?
[ "$status" -eq 1 ]
grep -q '^serde-gen: duplicate\.mbt-.*: duplicate annotated type First (first defined at first\.mbt-.*)$' error
[ ! -e duplicate.generated.mbt ]

# A package may contain unrelated, generated, test, and child-package files.
mkdir -p 'my package/child'
touch 'my package/moon.pkg' 'my package/child/moon.pkg'
cp second.mbt 'my package/z.mbt'
cp first.mbt 'my package/a.mbt'
cp first.mbt 'my package/child/ignored.mbt'
cp first.mbt 'my package/ignored.generated.mbt'
cp first.mbt 'my package/ignored_test.mbt'
cp first.mbt 'my package/ignored.js.mbt'
printf 'this is not valid MoonBit, but contains no marker\n' > 'my package/unmarked.mbt'
output='my package/serde.generated.mbt'
serde-gen --package 'my package'
cmp "$output" expected

cat > 'my package/a.mbt' <<'EOF'
#custom.serde
struct Edited {
  value : Int
}
EOF
mv 'my package/z.mbt' removed-source
cp first.mbt 'my package/new.mbt'
serde-gen --package 'my package'
grep -q 'impl ToJson for Edited ' "$output"
grep -q 'impl ToJson for First ' "$output"
if grep -q 'impl ToJson for Second ' "$output"; then
  echo 'A removed source still has a codec.' >&2
  exit 1
fi

mv 'my package/a.mbt' edited-source
mv 'my package/new.mbt' new-source
serde-gen --package 'my package'
[ "$(cat "$output")" = '// Generated by totto2727/serde. Do not edit.' ]
